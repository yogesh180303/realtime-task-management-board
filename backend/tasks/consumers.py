
from channels.db import database_sync_to_async
from channels.generic.websocket import AsyncJsonWebsocketConsumer

from workspaces.models import WorkspaceMembership


class TaskBoardConsumer(AsyncJsonWebsocketConsumer):

    @database_sync_to_async
    def is_workspace_member(self, user, workspace_id):
        return WorkspaceMembership.objects.filter(
            user=user,
            workspace_id=workspace_id,
        ).exists()

    async def connect(self):
        self.workspace_id = self.scope["url_route"]["kwargs"]["workspace_id"]
        user = self.scope["user"]

        if not user.is_authenticated:
            await self.close()
            return

        is_member = await self.is_workspace_member(
            user,
            self.workspace_id,
        )

        if not is_member:
            await self.close()
            return

        self.room_group_name = f"workspace_{self.workspace_id}"

        await self.channel_layer.group_add(
            self.room_group_name,
            self.channel_name,
        )

        await self.accept()

        await self.send_json({
            "type": "connection_established",
            "workspace_id": self.workspace_id,
            "message": "Connected to the workspace task board.",
        })

    async def disconnect(self, close_code):
        if hasattr(self, "room_group_name"):
            await self.channel_layer.group_discard(
                self.room_group_name,
                self.channel_name,
            )

    async def receive_json(self, content, **kwargs):
        if not isinstance(content, dict):
            await self.send_json({
                "type": "error",
                "message": "Invalid message format.",
            })
            return

        allowed_events = {
            "task_created",
            "task_updated",
            "task_deleted",
        }

        if content.get("type") not in allowed_events:
            await self.send_json({
                "type": "error",
                "message": "Unsupported event type.",
            })
            return

        await self.send_json({
            "type": "error",
            "message": "Task events are generated by the server.",
        })

    async def task_update(self, event):
        await self.send_json({
            "type": event["event"],
            "data": event["data"],
        })
